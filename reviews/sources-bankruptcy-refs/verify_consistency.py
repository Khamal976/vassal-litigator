# -*- coding: utf-8 -*-
"""Детектор внутренних противоречий: два места одного файла говорят об одной
норме противоположное.

Класс дефекта, ради которого написан скрипт. 2026-08-04 в справочнике по
субсидиарке §10.9 одновременно жили два правила о требовании по ст. 61.12,
поданном вне дела о банкротстве:

    врезка в начале раздела — «П. 51: заявление … как по основаниям ст. 61.11,
    так и по основаниям ст. 61.12 … рассматривается по правилам главы 28.2 АПК»
    последняя строка того же раздела — «Для требования по ст. 61.12 вне дела
    действуют правила искового производства (п. 5 ст. 61.19)»

Оба утверждения опираются на источник, оба выглядят связно, и ни одна из
машинных проверок их не видела: цитаты дословны (`verify_quotes`), адреса
существуют (`verify_addresses`), счёт сходится (`verify_counts`), ссылки целы
(`verify_links`). Нашёл противоречие человек — и только потому, что читал
раздел целиком. Цена: правка, писавшаяся по этому файлу, подхватила ошибочную
строку и разнесла её в скилл и в справочник по подсудности.

Что делает скрипт. Собирает по файлу все упоминания норм, группирует их и
внутри группы ищет пары фрагментов с ВЗАИМОИСКЛЮЧАЮЩИМИ маркерами — по
отрицанию («применяется» / «не применяется»), по режиму («глава 28.2» /
«исковое производство») и по числу («три рабочих дня» / «десять дней» при
одной норме).

Чего скрипт НЕ делает — и это существенно. Он не решает, кто прав, и не
утверждает, что противоречие есть: в юридическом тексте пара
взаимоисключающих утверждений сплошь и рядом законна — коллизия нормы и
разъяснения, правило и изъятие из него, «по букве так, на практике иначе».
Такие места автор обычно помечает сам («⚠», «но см.», «расхождение», «шире»,
«резервный довод»), и скрипт их отделяет в класс «конфликт описан явно».
Остаётся короткий список мест, где два правила стоят рядом молча — ровно то,
что надо прочитать глазами.

Допущение о пунктах без статьи. «П. 51», «п. 57 абз. 2» без указания статьи
внутри банкротного справочника — это пункты Пленума. Ключ таких упоминаний —
`Пленум п.51`; при работе с файлом, где номера пунктов принадлежат другому
акту, ключ будет тем же, а группировка — всё равно осмысленной, потому что
сравниваются упоминания внутри ОДНОГО файла.

Запуск:
    python verify_consistency.py <файл> [ещё файлы]
    python verify_consistency.py <файл> --all       # печатать и явные коллизии
    python verify_consistency.py <файл> --loose     # + группировка по статье целиком
    python verify_consistency.py <файл> --terms     # + ось сроков (шумная, см. ниже)

Ось сроков выключена по умолчанию. Идея была сильной — «три рабочих дня» и
«десять дней» при одной норме — но на реальных файлах она даёт почти весь шум
и ни одной находки: у ст. 61.2 и ст. 61.3 периодов подозрительности несколько
по самому закону (один месяц · шесть месяцев · один год · три года), и разные
числа при одной статье там НОРМА. В справочнике по оспариванию сделок эта ось
одна давала сорок пар из сорока семи. Включать точечно, когда сверяешь именно
сроки одного правила.

ЧЕГО СКРИПТ НЕ ВИДИТ — проверено двумя независимыми проверяющими 2026-08-04,
и об этом надо знать до того, как поверить его молчанию:

  * противоречия МЕЖДУ файлами. Индекс строится по одному файлу. Дефект,
    ради которого скрипт написан, разошёлся из справочника в скилл и в
    справочник по подсудности — вот этого распространения он бы не увидел;
  * расхождение с ПЕРВОИСТОЧНИКОМ. Если два места согласованы и оба неверны,
    скрипт молчит. Он проверяет связность, а не правильность;
  * перевороты без глагола применимости: разные пороги и суммы, разный круг
    лиц, «вправе / обязан». Модальные глаголы выброшены намеренно (шум);
  * разные объекты у одного глагола: «п. 69(1) не распространяется на
    управляющего» и «уступка не распространяется на превышение» попадут в
    одну пару. Это остаточный класс ложных срабатываний, регуляркой он не
    лечится и требует читателя.

Первый прогон по пяти банкротным справочникам дал 30 пар и НИ ОДНОГО
правового дефекта: 11 законных разведений (правило и изъятие), 19 ложных.
Ценность оказалась не в находках, а в карте швов — местах, где будущая
правка может потерять изъятие. Держать как генератор списка на вычитку, а не
как детектор ошибок.
"""
import sys, os, re

# --------------------------------------------------------------------------
# Извлечение ссылок на нормы
# --------------------------------------------------------------------------

# ⚠️ Границы обязательны. Без `(?!\d)` шаблон статьи откусывает начало более
# длинного номера: из «ст. 1080 ГК» получалась «ст. 108», и справочник по
# убыткам выдавал пять ложных пар «солидарно / в долях» по несуществующей
# норме. Тот же класс — в шаблоне срока ниже.
ART = r'(?:\d{1,4}(?:\.\d{1,2})?(?:-\d)?)(?!\d)'   # 61.19 · 225.10 · 333.21 · 61.6-1
ITEM = r'(?:\d{1,3}(?:\(\d{1,2}\))?)(?!\d)'        # 5 · 26(11) · 69(1)

# «п. 5 ст. 61.19», «пункта 2 статьи 61.15», «подп. 2 п. 4 ст. 61.10»
FULL = re.compile(
    r'(?:(?P<sub>подп\w*\.?|пп\.)\s*(?P<subn>' + ITEM + r')\s*[,)]?\s*)?'
    r'(?:(?P<it>п\w*\.?|пункт\w*)\s*(?P<itn>' + ITEM + r')\s*[,)]?\s*)?'
    r'(?P<st>ст\w*\.?|стать\w+)\s*(?P<stn>' + ART + r')'
    r'(?:\s*(?P<act>АПК|ГПК|КАС|НК|ГК|ТК|ФЗ-\d+|УК))?', re.I)

# «ч. 6 ст. 225.10 АПК» — часть кодекса
PART = re.compile(r'(?:ч\w*\.?|част\w+)\s*(?P<pn>\d{1,2}(?:\.\d)?)\s*'
                  r'(?:ст\w*\.?|стать\w+)\s*(?P<stn>' + ART + r')'
                  r'(?:\s*(?P<act>АПК|ГПК|КАС|НК|ГК|ТК))?', re.I)

# «п. 51», «п. 57 абз. 2», «пункт 26(11)» — пункт разъяснения, без статьи
BARE = re.compile(r'(?<![\w.])(?:п\.|пункт\w*)\s*(?P<n>' + ITEM + r')'
                  r'(?!\s*(?:ст|стать))', re.I)

# «глава 28.2», «гл. III.1»
CHAP = re.compile(r'(?:глав\w+|гл\.)\s*(?P<n>[IVX]+\.?\d*|\d{1,2}(?:\.\d)?)', re.I)


def norm_keys(text, loose=False):
    """Ключи норм, упомянутых во фрагменте. Точный ключ — статья с пунктом,
    грубый — статья целиком (нужен, когда одно правило описано через пункт
    Пленума, а другое — через пункт статьи: общее у них только статья)."""
    keys = set()
    for m in FULL.finditer(text):
        act = (m.group('act') or '').upper()
        st = m.group('stn')
        base = ('%s ст.%s' % (act, st)).strip()
        if m.group('itn'):
            keys.add('%s/п.%s' % (base, m.group('itn')))
            if m.group('subn'):
                keys.add('%s/п.%s/подп.%s' % (base, m.group('itn'), m.group('subn')))
        else:
            keys.add(base)
        if loose:
            keys.add(base)
    for m in PART.finditer(text):
        act = (m.group('act') or '').upper()
        keys.add(('%s ст.%s/ч.%s' % (act, m.group('stn'), m.group('pn'))).strip())
    for m in BARE.finditer(text):
        n = m.group('n')
        # Голые «п. 1», «п. 5», «п. 6» двусмысленны: столько же пунктов есть у
        # едва ли не каждой статьи главы III.2, и одинаковый номер сводит в одну
        # группу правила о разных нормах — источник ложных пар. Берём только те,
        # что заведомо принадлежат разъяснению: скобочная форма (26(5), 34(1),
        # 69(1)) либо номер выше двадцати (у Пленума № 53 их 96).
        if '(' in n or int(re.sub(r'\D.*', '', n) or 0) >= 20:
            keys.add('Пленум п.%s' % n)
    for m in CHAP.finditer(text):
        keys.add('глава %s' % m.group('n').rstrip('.'))
    return keys


# --------------------------------------------------------------------------
# Оси полярности: пары взаимоисключающих маркеров
# --------------------------------------------------------------------------

# Глаголы, у которых противоположность образуется отрицанием. Ловим сам глагол
# и наличие «не» непосредственно перед ним.
#
# Список намеренно короткий. В первой версии сюда входили «вправе», «может»,
# «нужно», «работает» — модальные глаголы общего употребления, и они дали
# почти весь шум: два правила об одной норме, где одно что-то разрешает, а
# другое чего-то не разрешает, — это норма юридического текста, а не
# противоречие. Остались глаголы, которыми описывают ПРИМЕНИМОСТЬ правила:
# именно на них строится ошибка «случай выведен из-под верного правила».
NEGABLE = [
    'применяетс', 'применим', 'распространяетс', 'относитс', 'требуетс',
    'допускаетс', 'восстанавливаетс', 'включаетс', 'переноситс', 'предусмотрен',
    'обязателен', 'обязательн', 'подлежит', 'засчитываетс', 'учитываетс',
    'прерываетс', 'приостанавливаетс', 'сохраняетс',
]
# `\b` перед альтернацией обязателен: без него «с**оотносится**» читается как
# «относится», и справочник по убыткам давал две ложные пары на обороте «как
# это соотносится с прежним правилом». Отрицание ловим в трёх формах: раздельное
# с окном до трёх слов («не во всех случаях применяется»), слитное
# («неприменим», «невосстановимы») и хвостовое («применяется, но не всегда»).
NEG_RE = re.compile(r'(?P<neg>\bне\s+(?:\w+\s+){0,3})?\b(?P<glued>не)?(?P<verb>' +
                    '|'.join(NEGABLE) + r')\w*'
                    r'(?P<tail>,?\s+но\s+не\s+(?:всегда|во\s+всех|в\s+полном))?', re.I)
SENT = re.compile(r'(?<=[.;!?])(?<!п\.)(?<!ст\.)(?<!абз\.)(?<!подп\.)'
                  r'(?<!пп\.)(?<!ч\.)(?<!гл\.)\s+(?=[А-ЯЁA-Z«*])')

# Пары режимов, исключающих друг друга без всякого «не».
MODES = [
    ('групповой иск (гл. 28.2)', r'глав\w+\s*28\.2|групповой иск|225\.1[0-6]',
     'исковое производство',     r'правил\w+\s+исковог\w+\s+производств'),
    # Ось «в деле / вне дела» была здесь и снята: почти каждая норма главы III.2
    # законно описывается и в обособленном споре, и вне дела — это маршруты, а
    # не противоречие. Она давала половину всего шума (в справочнике по убыткам
    # — двадцать пар из пятидесяти четырёх) и ни одной настоящей находки.
    ('солидарно',                r'солидарн',
     'в долях',                  r'\bв\s+дол\w+|долев\w+\s+ответственност'),
    ('текущее требование',       r'(?<!не )являетс\w*\s+текущ|(?<!не )относитс\w*\s+к\s+текущ',
     'реестровое требование',    r'реестров\w+\s+требован|не\s+являетс\w*\s+текущ'),
    ('бремя на заявителе',       r'дока\w+\s+заявител|бремя\s+(?:лежит\s+)?на\s+заявител|истец\s+доказ',
     'бремя на ответчике',       r'дока\w+\s+ответчик|бремя\s+(?:лежит\s+)?на\s+ответчик|презюмируетс'),
    ('срок восстановим',         r'восстанавливаетс\w*|подлежит\s+восстановлен|восстановлен\w+\s+срока',
     'срок невосстановим',       r'не\s+подлеж\w+\s+восстановлен|не\s+восстанавливаетс|восстановлен\w+\s+исключен'),
]
MODES = [(na, re.compile(ra, re.I), nb, re.compile(rb, re.I)) for na, ra, nb, rb in MODES]

# Сроки: число + единица. Разные сроки при одной норме — сильный сигнал.
# ⚠️ `(?<![\d.,])` обязателен: без него из «в 2025 году» извлекалось «025 год»,
# и файлы выдавали пары вида «срок: 25 год против 3 год». Правдоподобные
# пределы (LIMITS ниже) отсекают остаток дат и номеров.
TERM = re.compile(r'(?<![\d.,])(?P<n>\d{1,3}|один|два|три|четыре|пять|шесть|семь|восемь|девять|'
                  r'десять|пятнадцать|тридцат\w+|двух|трёх|трех|пяти|шести|десяти)[\s-]*'
                  r'(?P<u>рабочи\w+\s+дн\w+|календарн\w+\s+дн\w+|дн\w+|месяц\w*|год\w*|лет)', re.I)
LIMITS = {'раб.дн': 30, 'дн': 365, 'мес': 36, 'год': 15}   # выше — это дата, а не срок
TERMNUM = {'один': 1, 'два': 2, 'двух': 2, 'три': 3, 'трёх': 3, 'трех': 3, 'четыре': 4,
           'пять': 5, 'пяти': 5, 'шесть': 6, 'шести': 6, 'семь': 7, 'восемь': 8,
           'девять': 9, 'десять': 10, 'десяти': 10, 'пятнадцать': 15, 'тридцать': 30,
           'тридцати': 30}

# Автор знает о конфликте ИМЕННО ЭТИХ ДВУХ правил и говорит об этом — не находка.
#
# ⚠️ Сюда НЕЛЬЗЯ класть «⚠»: в этом проекте значок означает «важное», а не
# «коллизия», и стоит у каждой третьей врезки. Первая версия скрипта его
# включала — и глушила ровно тот случай, ради которого написана (пара
# «глава 28.2 / исковое производство» по ст. 61.12 находилась, но уходила в
# оговорённые, потому что врезка начиналась с ⚠). Маркер должен указывать на
# СООТНОШЕНИЕ правил, а не на их важность.
AWARE = re.compile(
    r'расхожд\w*|расход\w*тся|коллиз|но\s+см\.|см\.\s+врезк|против\s+нормы|\bшире\b|\bуже\b|'
    r'ýже|уже\s+норм|по\s+букве|резервн|'
    r'за\s+исключением[^.]{0,40}(?:п\.|ст\.|пункт|стать)|'
    r'не\s+путать|прежн\w+\s+редакц|прямого\s+разрешения|зеркальн|'
    r'ошибочн\w*\s+(?:была|было|редакц)|устарел|не\s+переноситс|переносить\s+нельзя|'
    r'сужен\w*\s+до|адресован\s+(?:субсидиарн|друг)', re.I)

# Строки, которые вообще не несут правил: журнальные и учётные. Их правила —
# пересказ задним числом («внесено: исправлен блокер — невосстановимы оба
# срока»), и в паре с настоящим разделом они дают ложное противоречие: в
# справочнике по субсидиарке две пары из четырёх пришли из строк Приложения А.
# Значок статуса в таблице стоит не в начале ячейки, а после номера строки
# реестра («| А.2 ✅ |»), поэтому ищем его в первых символах, а не сразу за «|».
SKIP_LINE = re.compile(r'^\s*(?:>\s*)?\|?\s*[А-ЯA-Z]?\.?\d{0,2}\s*(?:✅|⏳|❌)|^\s*\*\*Предыдущее|'
                       r'коммит|CHANGELOG|OPEN-ITEMS|проверя\w+\s+по\s+ос|'
                       r'^\s*#{1,4}\s*(?:§?17|Приложение|Источник)|'
                       r'\*\*Внесено:\*\*|Внесено:\s|хвост\s+закрыт', re.I)

QUOTE = re.compile(r'«[^»]{20,}»')


def polarity(frag):
    """Маркеры полярности во фрагменте: набор (ось, сторона)."""
    out = set()
    for m in NEG_RE.finditer(frag):
        verb = m.group('verb').lower()
        # «применим» и «применяется» — один вопрос; без сведения в одну ось
        # утверждение и его отрицание попадали в разные оси и не встречались.
        verb = 'применяетс' if verb.startswith('примен') else verb
        neg = bool(m.group('neg') or m.group('glued') or m.group('tail'))
        out.add(('не-' + verb, neg))
    for na, ra, nb, rb in MODES:
        a, b = bool(ra.search(frag)), bool(rb.search(frag))
        if a != b:                       # оба сразу — описание развилки, не сторона
            out.add((na + ' / ' + nb, a))
    return out


def terms(frag):
    """Сроки во фрагменте, нормализованные в (число, единица)."""
    out = set()
    for m in TERM.finditer(frag):
        tok = m.group('n').lower()
        n = int(tok) if tok.isdigit() else TERMNUM.get(tok.replace('ё', 'е'))
        if n is None:
            continue
        u = m.group('u').lower()
        u = ('раб.дн' if 'рабочи' in u else 'дн' if 'дн' in u else
             'мес' if 'месяц' in u else 'год')
        if n > LIMITS[u]:
            continue
        out.add((n, u))
    return out


def fragments(path):
    """Файл → список (строка, позиция в строке, фрагмент, ключи строки).

    Фрагмент — предложение либо ячейка таблицы: правило в юридическом тексте
    живёт в этих единицах, а не в строке файла (строка таблицы несёт до
    десятка независимых утверждений, абзац прозы — несколько правил).

    Позиция в строке нужна, чтобы сравнивать фрагменты ВНУТРИ одной строки.
    Первая версия отбрасывала такие пары (`if la == lb`), и это делало слепым
    сам класс, ради которого написан скрипт: в текущей редакции справочника
    обе стороны коллизии по ст. 61.12 стоят в одном абзаце — напиши автор их
    так сразу, скрипт бы промолчал.

    Ключи строки — ключи ПЕРВОЙ ячейки таблицы. В форме «| норма | правило |
    опора |» норма названа в заголовочной ячейке, а правило — в соседней, и
    без этого 44 % ячеек с правилами оставались без нормы, а часть получала
    норму соседней ячейки — то есть правило приписывалось не той норме."""
    out = []
    in_fence = False
    with open(path, encoding='utf-8') as f:
        for i, ln in enumerate(f.read().split('\n')):
            s = ln.strip()
            if s.startswith('```'):
                in_fence = not in_fence
                continue
            if in_fence or len(s) < 25 or SKIP_LINE.search(ln):
                continue
            is_table = s.startswith('|')
            cells = s.split('|') if is_table else [s]
            row_keys = norm_keys(cells[1]) if is_table and len(cells) > 1 else set()
            pos = 0
            for cell in cells:
                for part in SENT.split(cell):
                    part = part.strip(' *|')
                    if len(part) >= 25:
                        out.append((i + 1, pos, part, row_keys))
                        pos += 1
    if in_fence:
        print('   ⚠ код-фенс в файле не закрыт — часть текста не проверена')
    return out


def check(path, show_all=False, loose=False, with_terms=False):
    print('=' * 72)
    print('ФАЙЛ: %s' % os.path.basename(path))
    print('=' * 72)

    frags = fragments(path)
    index = {}
    n_norm = n_pol = n_both = 0
    orphan = []                     # правило есть, норма не названа — машина бессильна
    for line, pos, frag, row_keys in frags:
        pol, trm = polarity(frag), terms(frag)
        keys = norm_keys(frag, loose) | row_keys
        if keys:
            n_norm += 1
        if pol or trm:
            n_pol += 1
        if not (pol or trm):
            continue
        if not keys:
            orphan.append((line, frag))
            continue
        n_both += 1
        for key in keys:
            index.setdefault(key, []).append((line, pos, frag, pol, trm))

    silent, aware, seen = [], [], set()
    for key in sorted(index):
        items = index[key]
        if len(items) < 2:
            continue
        if len(items) > 60:         # патологическая группа: пар квадратично много
            print('   ⚠ норма %s упомянута %d раз — пары по ней не строились'
                  % (key, len(items)))
            continue
        for i in range(len(items)):
            for j in range(i + 1, len(items)):
                la, pia, fa, pa, ta = items[i]
                lb, pib, fb, pb, tb = items[j]
                if (la, pia) == (lb, pib) or fa == fb:
                    continue
                axes = []
                for axis, side in pa:
                    if (axis, not side) in pb:
                        axes.append(axis)
                if with_terms:
                    for n, u in ta:
                        for n2, u2 in tb:
                            if u == u2 and n != n2:
                                axes.append('срок: %d %s против %d %s' % (n, u, n2, u2))
                if not axes:
                    continue
                sig = (la, pia, lb, pib, tuple(sorted(set(axes))))
                if sig in seen:      # та же пара под другим ключом (ст.X и ст.X/п.N)
                    continue
                seen.add(sig)
                rec = (key, la, fa, lb, fb, sorted(set(axes)))
                (aware if (AWARE.search(fa) or AWARE.search(fb)) else silent).append(rec)

    def show(recs, title):
        print()
        print(title)
        for key, la, fa, lb, fb, axes in recs:
            print()
            print('  [%s] ось: %s' % (key, '; '.join(axes)))
            print('    стр. %-5d %s' % (la, cut(fa)))
            print('    стр. %-5d %s' % (lb, cut(fb)))
            for f, l in ((fa, la), (fb, lb)):
                if QUOTE.search(f):
                    print('       ^ стр. %d содержит дословную цитату — сверить, '
                          'не пересказ ли вторая' % l)
                    break

    # Расстояние между местами — сильный признак. Два правила в одном абзаце
    # или в соседних строках таблицы почти всегда написаны одной рукой за один
    # присест: «к X применяется, к Y нет» — это разведение, а не противоречие.
    # Опасны разошедшиеся места: там автор второй раз писал о той же норме, не
    # видя первого правила. Целевой дефект захода — стр. 913 против 944.
    near = [r for r in silent if abs(r[1] - r[3]) < 3]
    far = [r for r in silent if abs(r[1] - r[3]) >= 3]
    if far:
        show(far, '- - - ПРАВИЛА В РАЗНЫХ МЕСТАХ ФАЙЛА, КОНФЛИКТ НЕ ОГОВОРЁН - - -')
    if near and show_all:
        show(near, '- - - правила рядом (обычно разведение «к X да, к Y нет») - - -')
    if aware and show_all:
        show(aware, '- - - конфликт описан явно (коллизия, изъятие, журнал) - - -')

    # Границы применимости печатаются всегда: молчание этого скрипта — не
    # «противоречий нет», а «среди сравнимых фрагментов встречных пар нет».
    # Сравнимо около 5 % текста справочника, и об этом надо говорить вслух.
    print()
    print('-' * 72)
    print('ИТОГ %s: врозь %d · рядом %d · оговорено %d%s'
          % (os.path.basename(path), len(far), len(near), len(aware),
             '' if show_all else ' (два последних — --all)'))
    print('   охват: фрагментов %d · с нормой %d · с правилом %d · сравнивалось %d (%.0f %%)'
          % (len(frags), n_norm, n_pol, n_both, 100.0 * n_both / max(1, len(frags))))
    print('   ключей норм в индексе %d · ось сроков %s'
          % (len(index), 'включена' if with_terms else 'выключена (--terms)'))
    if orphan:
        print('   правило есть, норма не названа — машина бессильна: %d фрагментов'
              % len(orphan))
    return len(far)


def cut(s, n=96):
    s = re.sub(r'\s+', ' ', s)
    return s if len(s) <= n else s[:n - 3] + '...'


FLAGS = {'--all', '--loose', '--terms'}


def main():
    # ⚠️ Windows-консоль по умолчанию не в UTF-8, и первый же фрагмент со
    # значком «⚠» роняет печать с UnicodeEncodeError — ровно на находке,
    # потому что значок стоит у самых важных врезок. Отчёт обрывался посреди
    # списка, а человек видел трейсбек вместо итога.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding='utf-8', errors='replace')
        except Exception:
            pass

    bad = [a for a in sys.argv[1:] if a.startswith('--') and a not in FLAGS]
    if bad:
        print('НЕИЗВЕСТНЫЙ ФЛАГ: %s (известные: %s)'
              % (', '.join(bad), ', '.join(sorted(FLAGS))))
        return 2
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if not args:
        print(__doc__)
        return 1
    missing = [p for p in args if not os.path.exists(p)]
    if missing:
        # Молчание — заключение этого скрипта, поэтому опечатка в пути не
        # должна выглядеть как чистый файл.
        print('НЕ НАЙДЕН ФАЙЛ: %s' % ', '.join(missing))
    total = sum(check(p, '--all' in sys.argv, '--loose' in sys.argv,
                      '--terms' in sys.argv)
                for p in args if os.path.exists(p))
    print()
    print('=' * 72)
    print('ВСЕГО МЕСТ ДЛЯ ЧТЕНИЯ ГЛАЗАМИ: %d' % total)
    print('Скрипт не решает, кто прав, и не утверждает, что это ошибка:')
    print('пара взаимоисключающих правил бывает законной. Он показывает пары,')
    print('которые стоят в файле МОЛЧА — без пометки о коллизии или изъятии.')
    print()
    print('Молчание скрипта НЕ означает «противоречий нет»: он сравнивает только')
    print('фрагменты, где названа норма И высказано правило о её применимости —')
    print('это около 5 % текста справочника. Противоречия МЕЖДУ файлами он не')
    print('видит вовсе, и расхождение с первоисточником — тоже (оба места могут')
    print('быть согласованы и одинаково неверны).')
    return 2 if missing else (1 if total else 0)


if __name__ == '__main__':
    sys.exit(main())
